export type ReleaseClass = 'major' | 'minor' | 'patch';

export interface SurfaceChange {
  class: ReleaseClass;
  breaking: string[];
  additive: string[];
  /** Changes a human must read: real, but not classifiable from a digest. */
  review: string[];
}

const CLASS_RANK: Record<ReleaseClass, number> = { patch: 0, minor: 1, major: 2 };

/**
 * Classify the difference between two surfaces.
 *
 * Reports EVERY reason rather than the first, because a release usually carries
 * several and a guard that stops at one teaches its reader to fix-and-rerun
 * instead of reading.
 */
export function classifySurfaceChange(
  before: ReleaseSurface,
  after: ReleaseSurface
): SurfaceChange {
  const breaking: string[] = [];
  const additive: string[] = [];
  const review: string[] = [];

  if (before.contractVersion !== after.contractVersion) {
    breaking.push(
      `substrate contract range moved ${before.contractVersion} -> ${after.contractVersion}`
    );
  }

  for (const typeName of Object.keys(before.types)) {
    if (!Object.hasOwn(after.types, typeName)) {
      breaking.push(`type removed: ${typeName}`);
      continue;
    }
    const b = before.types[typeName] ?? {};
    const a = after.types[typeName] ?? {};

    for (const fieldName of Object.keys(b)) {
      const bf = b[fieldName];
      const af = a[fieldName];
      const at = `${typeName}.${fieldName}`;
      if (bf === undefined) continue;
      if (af === undefined) {
        breaking.push(`field removed: ${at}`);
        continue;
      }
      if (bf.kind !== af.kind) breaking.push(`field kind changed: ${at} ${bf.kind} -> ${af.kind}`);
      if (bf.type !== af.type && (bf.type ?? af.type) !== undefined) {
        breaking.push(`field type changed: ${at} ${bf.type ?? '?'} -> ${af.type ?? '?'}`);
      }
      if (bf.target !== af.target && (bf.target ?? af.target) !== undefined) {
        breaking.push(`crossRef target changed: ${at} ${bf.target ?? '?'} -> ${af.target ?? '?'}`);
      }
      // Optional -> required breaks every existing writer.
      if (!bf.required && af.required) breaking.push(`field became REQUIRED: ${at}`);
      if (bf.required && !af.required) additive.push(`field relaxed to optional: ${at}`);
      // Nullable -> non-nullable breaks every existing ROW carrying a null.
      if (bf.nullable && !af.nullable) breaking.push(`field no longer nullable: ${at}`);
      // Un-indexing turns an index-served filter into a scan of the type.
      if (bf.indexed && !af.indexed) review.push(`field no longer indexed: ${at}`);
      if (!bf.indexed && af.indexed) additive.push(`field now indexed: ${at}`);

      const bEnum = bf.enum ?? null;
      const aEnum = af.enum ?? null;
      if (bEnum !== null && aEnum === null) additive.push(`enum constraint dropped: ${at}`);
      if (bEnum === null && aEnum !== null) breaking.push(`enum constraint added: ${at}`);
      if (bEnum !== null && aEnum !== null) {
        const removed = bEnum.filter((v) => !aEnum.includes(v));
        const added = aEnum.filter((v) => !bEnum.includes(v));
        // Narrowing rejects values already stored; widening cannot.
        if (removed.length > 0) breaking.push(`enum narrowed: ${at} lost ${removed.join(', ')}`);
        if (added.length > 0) additive.push(`enum widened: ${at} gained ${added.join(', ')}`);
      }
    }

    for (const fieldName of Object.keys(a)) {
      if (Object.hasOwn(b, fieldName)) continue;
      const af = a[fieldName];
      if (af === undefined) continue;
      const at = `${typeName}.${fieldName}`;
      // A new REQUIRED field breaks every existing writer, so it is not additive.
      if (af.required) breaking.push(`field added as REQUIRED: ${at}`);
      else additive.push(`field added: ${at}`);
    }
  }

  for (const typeName of Object.keys(after.types)) {
    if (!Object.hasOwn(before.types, typeName)) additive.push(`type added: ${typeName}`);
  }

  // Published TypeScript API, if the snapshot carries one. Absent on a surface
  // written before `api` existed — treated as "not compared" rather than
  // "nothing exported", which would report every export as newly added.
  const bApi = before.api ?? null;
  const aApi = after.api ?? null;
  // A format change renames every entry without touching the API. Comparing
  // across it would report the whole surface removed and re-added — a fake
  // MAJOR produced by tooling. Not compared, and SAID so, rather than silently
  // skipped: an unexplained absence is the thing this guard exists to prevent.
  const bFormat = before.surfaceFormat ?? 1;
  const aFormat = after.surfaceFormat ?? 1;
  if (bApi !== null && aApi !== null && bFormat !== aFormat) {
    review.push(
      `published-API comparison SKIPPED: surface format ${bFormat} -> ${aFormat}. The export ` +
        'naming scheme changed, so a diff would be noise rather than signal. Size this release ' +
        'from the type section above and from reading the .d.ts diff by hand.'
    );
  } else if (bApi !== null && aApi !== null) {
    for (const pkg of Object.keys(bApi)) {
      const b = bApi[pkg];
      const a = aApi[pkg];
      if (b === undefined) continue;
      if (a === undefined) {
        breaking.push(`package no longer published: ${pkg}`);
        continue;
      }
      for (const name of b.exports) {
        if (!a.exports.includes(name)) breaking.push(`export removed: ${pkg}#${name}`);
      }
      for (const name of a.exports) {
        if (!b.exports.includes(name)) additive.push(`export added: ${pkg}#${name}`);
      }
      if (b.dtsDigest !== a.dtsDigest) {
        review.push(
          `${pkg}: emitted declarations changed (${b.dtsDigest} -> ${a.dtsDigest}). ` +
            'A signature moved somewhere in this package. Read the .d.ts diff and decide ' +
            'whether it breaks a caller — this cannot tell a widened return type from a ' +
            'narrowed one.'
        );
      }
    }
    for (const pkg of Object.keys(aApi)) {
      if (!Object.hasOwn(bApi, pkg)) additive.push(`package now published: ${pkg}`);
    }
  }

  // A review item raises the floor to minor: something in the published API
  // moved, and a patch asserts nothing did.
  const cls: ReleaseClass =
    breaking.length > 0 ? 'major' : additive.length > 0 || review.length > 0 ? 'minor' : 'patch';
  return { class: cls, breaking, additive, review };
}

/** Is `proposed` at least as large as `required`? */
export function classSatisfies(proposed: ReleaseClass, required: ReleaseClass): boolean {
  return CLASS_RANK[proposed] >= CLASS_RANK[required];
}

/** The class implied by a version bump. Returns null when it is not a bump. */
export function bumpClass(from: string, to: string): ReleaseClass | null {
  const p = (v: string): [number, number, number] => {
    const [a = Number.NaN, b = Number.NaN, c = Number.NaN] = v
      .trim()
      .replace(/^v/, '')
      .split('.')
      .map(Number);
    return [a, b, c];
  };
  const [fa, fb, fc] = p(from);
  const [ta, tb, tc] = p(to);
  if ([fa, fb, fc, ta, tb, tc].some((n) => !Number.isFinite(n))) return null;
  if (ta > fa) return 'major';
  if (ta === fa && tb > fb) return 'minor';
  if (ta === fa && tb === fb && tc > fc) return 'patch';
  return null;
}
