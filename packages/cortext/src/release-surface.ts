/**
 * The plugin-facing surface, snapshotted so a release can be SIZED rather than
 * judged.
 *
 * ## Why this exists
 *
 * A release-class guard that defines the surface as a list of paths passes a
 * major as a patch with a green check the moment a type moves out of those
 * paths: `git diff` on the stale path is empty, so it approves.
 *
 * cortext's propagation is heavy — a
 * `packages/cortext/src` change reaches consumers as an npm tarball loaded by
 * the substrate runtime from `SUBSTRATE_PLUGIN_DIR`, needing a publish **and** a
 * runtime deploy. npm publishes are immutable, so a mis-sized release cannot be
 * withdrawn, only superseded.
 *
 * ## Why it resolves through the code, not through paths
 *
 * A path list rots silently. This calls
 * `buildClaudeNamespace()` and walks what it returns, so the surface is
 * DERIVED from the thing it describes. A type or field cannot move out from
 * under it, because there is no "under it" — moving a declaration between files
 * changes nothing here, and that is the point.
 *
 * The committed `release-surface.json` is kept honest by
 * `test/release-surface.test.ts`, exactly as `config.schema.json` is kept
 * honest by `schema-parity.test.ts`. So the release script never has to execute
 * TypeScript or parse a declaration: it diffs two committed JSON snapshots.
 *
 * ## What counts as breaking, and why `indexed` is in here
 *
 * Removing a type or field, making an optional field REQUIRED, narrowing an
 * enum, or moving the substrate contract range are all breaks for someone holding
 * data or code against this schema.
 *
 * `indexed` is included as a review item, not a break: every field filters,
 * so un-indexing one turns an index-served `where` into a scan of the type.
 * The caller's query still works, but slower, and a human should weigh it.
 */

import { SUBSTRATE_CONTRACT_RANGE } from './kernel/index.js';
import { buildClaudeNamespace } from './namespace.js';

/** One field, reduced to the properties a consumer can break against. */
export interface SurfaceField {
  kind: string;
  type?: string;
  /** crossRef target type. */
  target?: string;
  nullable: boolean;
  hasDefault: boolean;
  readonly: boolean;
  serverSet: boolean;
  indexed: boolean;
  enum?: string[];
  /** Not (nullable | default | readonly | serverSet) — the write contract. */
  required: boolean;
}

/**
 * The published TypeScript API of one package.
 *
 * Two signals with deliberately different precision, because one alone is not
 * enough and the gap between them is where a real break just hid:
 *
 * - `exports` is PRECISE. A name that disappears is a hard break; a name that
 *   appears is additive. No ambiguity either way.
 * - `dtsDigest` NEVER MISSES. It hashes every emitted declaration, so any
 *   signature change anywhere moves it — but it cannot say WHICH export moved.
 *
 * The digest exists because of a live miss: `auditObjects` kept its name and
 * changed its return type from `Finding[]` to `{ findings, checked }`. Names
 * alone saw nothing. A schema-only surface saw nothing. It is exported from
 * the kernel plugin's entry point, so it is a published break, and it was
 * about to ship under a patch.
 *
 * A digest change therefore raises the floor to MINOR and is reported for a
 * human to read — never auto-major, because it cannot tell a widened return
 * type from a narrowed one.
 */
export interface PackageApi {
  /**
   * Exported names qualified by the subpath that publishes them, as
   * `<subpath>:<name>` — e.g. `.:buildReleaseSurface`, `./bootstrap:bootstrap`.
   *
   * Qualified rather than a bare union because the union cannot see a MOVE.
   * A name relocated from `.` to `./bootstrap` breaks every existing importer
   * while leaving a union identical; qualified, it reads as one removal and one
   * addition, which is exactly what it is. The set diff below needs no change
   * to get that right — the qualification does all the work.
   */
  exports: string[];
  dtsDigest: string;
}

/**
 * Format marker for the `api` section.
 *
 * Bumped when the SHAPE of `api` changes rather than its content. The exports
 * list moved from bare names to subpath-qualified ones, which would otherwise
 * read as every export being removed and re-added — a fake MAJOR generated by a
 * tooling change that touched no published API.
 *
 * `classifySurfaceChange` treats a format mismatch as NOT COMPARED, the same
 * way it already treats an absent `api`. That is the honest reading and it is
 * an existing precedent in this file rather than a special case invented for
 * this bump.
 */
export const SURFACE_FORMAT = 2;

export interface ReleaseSurface {
  contractVersion: string;
  types: Record<string, Record<string, SurfaceField>>;
  api?: Record<string, PackageApi>;
  /** Absent means format 1 — bare, root-entry-only export names. */
  surfaceFormat?: number;
}

/** One published entry point: the subpath a consumer imports, and its `.d.ts`. */
export interface SurfaceEntry {
  subpath: string;
  dts: string;
}

/**
 * Resolve the `.d.ts` each published subpath points at, from a package's
 * `exports` map.
 *
 * ## Why this exists
 *
 * The previous version assumed one entry per package and read `dist/index.d.ts`.
 * Every publishable package here is multi-entry, so `./bootstrap`'s three
 * exports — `bootstrap`, `CortextBootstrapConfig`,
 * `CortextBootstrapConfigSchema` — were never in the exports list at all.
 * Measured against the real classifier before fixing:
 *
 *     additive change in ./bootstrap    guard MINOR   correct MINOR   right
 *     export REMOVED from ./bootstrap   guard MINOR   correct MAJOR   UNDER-SIZED
 *     export removed from "."           guard MAJOR   correct MAJOR   right
 *
 * The middle row is the defect. It survived because the `dtsDigest` half of the
 * two-signal design DOES cover every emitted declaration, so the change was
 * never invisible — it was merely floored at minor by a review item. A guard
 * that is wrong in one direction only is the hard kind to notice.
 *
 * ## Returns nothing rather than guessing
 *
 * A package with no `exports` map gets the conventional single entry. A subpath
 * publishing no `types` condition contributes nothing — it exposes no
 * TypeScript surface to compare. Neither is an error.
 *
 * Missing FILES are an error, and that is deliberate: silently skipping a
 * declared subpath whose layout does not match the assumption would recreate
 * exactly the blind spot this function removes — an unread surface reporting
 * clean. The caller supplies `exists` so this stays pure.
 */
export function resolveSurfaceEntries(
  exportsMap: unknown,
  exists: (relPath: string) => boolean
): Array<{ subpath: string; dtsPath: string }> {
  if (exportsMap === null || exportsMap === undefined || typeof exportsMap !== 'object') {
    return exists('dist/index.d.ts') ? [{ subpath: '.', dtsPath: 'dist/index.d.ts' }] : [];
  }
  const out: Array<{ subpath: string; dtsPath: string }> = [];
  for (const [subpath, conditions] of Object.entries(exportsMap as Record<string, unknown>)) {
    if (conditions === null || conditions === undefined) continue;
    const types =
      typeof conditions === 'string'
        ? conditions
        : ((conditions as Record<string, unknown>).types ?? null);
    // No `types` condition means no TypeScript surface published at this
    // subpath. Not every export is code — a package may map a subpath to a
    // config file — and handing that to a .d.ts parser produces nonsense
    // rather than an error.
    if (typeof types !== 'string' || !types.endsWith('.d.ts')) continue;
    const dtsPath = types.replace(/^\.\//, '');
    if (!exists(dtsPath)) {
      throw new Error(
        `release-surface: subpath '${subpath}' publishes '${dtsPath}', which does not exist. ` +
          'Either the package is not built, or the exports map points somewhere this resolver ' +
          'does not understand. Teach it the layout — do not let the subpath go unread.'
      );
    }
    out.push({ subpath, dtsPath });
  }
  return out.sort((a, b) => a.subpath.localeCompare(b.subpath));
}

interface RawField {
  kind?: unknown;
  type?: unknown;
  nullable?: unknown;
  default?: unknown;
  readonly?: unknown;
  serverSet?: unknown;
  indexed?: unknown;
  enum?: unknown;
  of?: unknown;
}

function reduceField(raw: RawField): SurfaceField {
  const nullable = raw.nullable === true;
  const hasDefault = Object.hasOwn(raw, 'default');
  const readonly = raw.readonly === true;
  const serverSet = raw.serverSet !== undefined && raw.serverSet !== false;
  const out: SurfaceField = {
    kind: typeof raw.kind === 'string' ? raw.kind : 'unknown',
    nullable,
    hasDefault,
    readonly,
    serverSet,
    indexed: raw.indexed === true,
    // The same rule the cold-start write-contract digest uses, deliberately:
    // two places deriving "required" differently would be a defect generator.
    required: !(nullable || hasDefault || readonly || serverSet)
  };
  if (typeof raw.type === 'string') {
    // crossRef stores its TARGET type under the same key a scalar uses for its
    // primitive. Splitting them keeps a scalar->crossRef change visible as a
    // kind change rather than hiding inside one field.
    if (out.kind === 'crossRef') out.target = raw.type;
    else out.type = raw.type;
  }
  if (Array.isArray(raw.enum)) out.enum = [...(raw.enum as string[])].sort();
  if (out.kind === 'list' && raw.of !== null && typeof raw.of === 'object') {
    const inner = raw.of as RawField;
    if (typeof inner.type === 'string') out.type = `list<${inner.type}>`;
  }
  return out;
}

/**
 * Build the canonical surface.
 *
 * Keys are sorted so the committed JSON is stable — an unstable snapshot would
 * produce diff noise on every regeneration and train its reader to skim, which
 * is the failure this whole file is guarding against one level down.
 */
export function buildReleaseSurface(namespace = 'cortext'): ReleaseSurface {
  const ns = buildClaudeNamespace(namespace) as unknown as {
    types: Record<string, { fields: Record<string, RawField> }>;
  };
  const types: Record<string, Record<string, SurfaceField>> = {};
  for (const typeName of Object.keys(ns.types).sort()) {
    const declared = ns.types[typeName]?.fields ?? {};
    const fields: Record<string, SurfaceField> = {};
    for (const fieldName of Object.keys(declared).sort()) {
      const raw = declared[fieldName];
      if (raw === undefined) continue;
      fields[fieldName] = reduceField(raw);
    }
    types[typeName] = fields;
  }
  return { contractVersion: SUBSTRATE_CONTRACT_RANGE, types };
}

/**
 * Extract the public export NAMES from an entry `.d.ts`.
 *
 * Handles the two forms tsdown emits: re-export lists (`export { a, type B }
 * from './x.js'`) and direct declarations (`export declare function f`). The
 * `type` modifier and `as` aliases are normalised to the exported name, since
 * that is what a consumer writes.
 */
export function parseDtsExports(dts: string): string[] {
  const names = new Set<string>();

  for (const m of dts.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const raw of (m[1] ?? '').split(',')) {
      const part = raw.trim();
      if (part.length === 0) continue;
      // `type Foo`, `Foo as Bar`, `default as Foo`
      const asMatch = /(?:^|\s)as\s+(\w+)$/.exec(part);
      const name = asMatch !== null ? asMatch[1] : part.replace(/^type\s+/, '').trim();
      if (name !== undefined && /^\w+$/.test(name)) names.add(name);
    }
  }
  for (const m of dts.matchAll(
    /export\s+(?:declare\s+)?(?:async\s+)?(?:function|const|let|var|class|interface|type|enum)\s+(\w+)/g
  )) {
    if (m[1] !== undefined) names.add(m[1]);
  }
  return [...names].sort();
}

/**
 * Build the published-API section.
 *
 * File reading is the CALLER's job — this stays pure so the rules are testable
 * without a build directory, matching every other classifier in this file.
 *
 * @param entries One per published package: EVERY published entry point (see
 *   `resolveSurfaceEntries`), plus the text of every emitted declaration file
 *   for the digest.
 * @param digest A hashing function; injected so this module needs no node
 *   built-ins and can run anywhere the rest of it can.
 */
export function buildApiSurface(
  entries: ReadonlyArray<{
    name: string;
    entries: ReadonlyArray<SurfaceEntry>;
    allDts: ReadonlyArray<string>;
  }>,
  digest: (input: string) => string
): Record<string, PackageApi> {
  const api: Record<string, PackageApi> = {};
  for (const e of [...entries].sort((x, y) => x.name.localeCompare(y.name))) {
    const names = new Set<string>();
    for (const entry of e.entries) {
      for (const name of parseDtsExports(entry.dts)) names.add(`${entry.subpath}:${name}`);
    }
    api[e.name] = {
      exports: [...names].sort(),
      // Sorted before joining so the digest is stable across filesystem order.
      dtsDigest: digest([...e.allDts].sort().join('\n'))
    };
  }
  return api;
}

